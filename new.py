# ENERGY CONSUMPTION ANOMALY DETECTION

# 1. Import libraries
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.ensemble import IsolationForest
import zipfile
import os


# 2. Load electricity dataset

# Define paths
zip_file_path = "/content/individual+household+electric+power+consumption.zip"
extracted_dir = "/content/extracted_data/" # Create a subdirectory for extracted files
os.makedirs(extracted_dir, exist_ok=True) # Ensure the directory exists

# Unzip the file
if zipfile.is_zipfile(zip_file_path):
    with zipfile.ZipFile(zip_file_path, 'r') as zip_ref:
        zip_ref.extractall(extracted_dir)
    print(f"Contents of {zip_file_path} extracted to {extracted_dir}")

    # Assuming there's one CSV or TXT file inside and it's named similarly
    extracted_files = os.listdir(extracted_dir)
    csv_file_name = None
    for f in extracted_files:
        # The original filename suggests it might be a .txt file inside
        if f.endswith('.txt') or f.endswith('.csv'):
            csv_file_name = f
            break

    if csv_file_name:
        csv_file_path = os.path.join(extracted_dir, csv_file_name)
        print(f"Reading CSV from: {csv_file_path}")
        df = pd.read_csv(
            csv_file_path,
            sep=";",
            na_values="?",
            low_memory=False,
            encoding='latin1' # Retain encoding as the actual CSV content might need it
        )
    else:
        raise FileNotFoundError("No CSV or TXT file found inside the zip archive.")
else:
    raise FileNotFoundError(f"{zip_file_path} is not a valid zip file or is not found.")

# 3. Select electricity consumption column
df = df[['Global_active_power']]

# 4. Clean the data
df = df.dropna()

# 5. Convert data into numeric format
df['Global_active_power'] = pd.to_numeric(
    df['Global_active_power']
)

# 6. Convert data into hourly average
hourly_data = df['Global_active_power'].iloc[::60]

# 7. Prepare data for ML
X = hourly_data.values.reshape(-1, 1)

# 8. Create ML model
model = IsolationForest(
    contamination=0.05,
    random_state=42
)

# 9. Train model
model.fit(X)

# 10. Predict anomalies
predictions = model.predict(X)

# 11. Display results
# Create a new DataFrame for results based on hourly_data
result = pd.DataFrame({
    'Energy_Consumption': hourly_data.values,
    'Prediction': predictions
})

result['Status'] = result['Prediction'].apply(
    lambda x: 'Normal' if x == 1 else 'Anomaly'
)

print(result.head(20))

print("\nDetected Anomalies:")
print(result[result['Status'] == 'Anomaly'])

# 12. Visualize results
plt.figure(figsize=(12, 5))

plt.plot(
    hourly_data.index,
    hourly_data.values,
    label='Energy Consumption'
)

anomaly_indices = result[result['Status'] == 'Anomaly'].index
anomaly_values = result[result['Status'] == 'Anomaly']['Energy_Consumption']

plt.scatter(
    hourly_data.index[anomaly_indices],
    hourly_data.values[anomaly_indices],
    color='red',
    label='Anomaly'
)

plt.xlabel("Reading Number")
plt.ylabel("Global Active Power (kW)")
plt.title("Energy Consumption Anomaly Detection")

plt.legend()
plt.show()

